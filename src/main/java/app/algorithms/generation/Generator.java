package app.algorithms.generation;

import app.configuration.CurrentSize;
import app.maze.Maze;

/**
 * Интерфейс, определяющий контракт для алгоритмов генерации лабиринта.
 * Реализации должны предоставлять способ генерации лабиринта заданного размера
 * и возвращать его имя для отображения пользователю.
 *
 * @author unknown
 * @version 1.0
 */
public interface Generator {

    /**
     * Генерирует лабиринт на основе указанных размеров.
     *
     * @param size размеры лабиринта (высота и ширина в ячейках)
     * @return объект {@link Maze}, представляющий сгенерированный лабиринт
     */
    Maze generate(CurrentSize size);

    /**
     * Возвращает имя алгоритма генерации для отображения в интерфейсе пользователя.
     *
     * @return строковое название алгоритма с кратким описанием
     */
    String getName();
}