package app.algorithms.solution;

import app.maze.Coordinate;
import app.maze.Maze;
import java.util.List;

/**
 * Интерфейс, определяющий контракт для алгоритмов поиска пути в лабиринте.
 * Реализации должны предоставлять способ нахождения маршрута между двумя точками,
 * а также возвращать своё имя для отображения пользователю.
 *
 * @author unknown
 * @version 1.0
 */
public interface Solver {

    /**
     * Находит путь между заданными начальной и конечной координатами в указанном лабиринте.
     *
     * @param maze  лабиринт, в котором ищется путь
     * @param start начальная координата
     * @param end   конечная координата
     * @return список координат от start до end (включая обе конечные точки),
     *         или пустой список, если путь не найден или начальная/конечная ячейки
     *         не являются проходами
     */
    List<Coordinate> solve(Maze maze, Coordinate start, Coordinate end);


    /**
     * Находит путь от входа к выходу лабиринта, используя встроенные координаты
     * входа и выхода из объекта {@link Maze}.
     *
     * @param maze лабиринт, в котором ищется путь
     * @return список координат от входа до выхода (включая обе конечные точки),
     *         или пустой список, если путь не найден
     */
    List<Coordinate> solve(Maze maze);


    /**
     * Возвращает имя алгоритма поиска пути для отображения в интерфейсе пользователя.
     *
     * @return строковое название алгоритма с кратким описанием
     */
    String getName();
}